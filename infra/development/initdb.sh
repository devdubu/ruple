#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  --set=database="$POSTGRES_DB" \
  --set=migration_password="$RUPLE_MIGRATION_PASSWORD" \
  --set=runtime_password="$RUPLE_RUNTIME_PASSWORD" <<'SQL'
CREATE ROLE ruple_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'migration_password';
CREATE ROLE ruple_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'runtime_password';
REVOKE ALL ON DATABASE :"database" FROM PUBLIC;
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;
GRANT CONNECT, CREATE ON DATABASE :"database" TO ruple_migrator;
GRANT CONNECT ON DATABASE :"database" TO ruple_runtime;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA app AUTHORIZATION ruple_migrator;
GRANT USAGE ON SCHEMA app TO ruple_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE ruple_migrator IN SCHEMA app GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ruple_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE ruple_migrator IN SCHEMA app GRANT USAGE, SELECT ON SEQUENCES TO ruple_runtime;
SQL
